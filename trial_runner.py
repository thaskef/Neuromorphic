    from genome_compiler import GenomeCompiler
    from sample_genome_dms import create_dms_genome

    b2.start_scope()

    genome = create_dms_genome(
        name="trial_demo",
        n_features=2,
        n_neurons_per_feature=20,
        n_associative=150,
        n_inhibitory=40,
    )
    compiler = GenomeCompiler(seed=3)
    net = compiler.compile(genome)

    runner = TrialRunner(
        network=net,
        n_features=2,
        n_neurons_per_feature=20,
        rate_on=50.0,
        input_weight=20.0,
        readout_threshold=0.3,
        seed=3,
    )

    for label, is_match in (("MATCH", True), ("NON-MATCH", False)):
        stimuli = runner.generate_stimuli()
        # force the ground-truth label for the demo
        stimuli.test_is_match = is_match
        stimuli.test = stimuli.sample.copy() if is_match else 1 - stimuli.sample
        result = runner.run_trial(stimuli)
        assoc_rates = {
            p: f"{s.firing_rate:.2f}" for p, s in result.phase_stats.items()
        }
        print(f"\n{label} trial: sample={stimuli.sample}, test={stimuli.test}")
        print(f"  decision={'match' if result.decision else 'non-match'} "
              f"correct={result.correct} reward={result.reward:+.0f} "
              f"similarity={result.similarity:.3f}")
        print(f"  assoc rates (Hz) by phase: {assoc_rates}")
        print(f"  sensory sample rates: {np.round(result.sensory_sample_rates, 1)}")
        print(f"  sensory test rates:   {np.round(result.sensory_test_rates, 1)}")
