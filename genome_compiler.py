def create_simple_stdp_network(
    n_exc: int = 8000,
    n_inh: int = 2000,
    conn_prob: float = 0.02,
    w_exc: float = 0.5,
    w_inh: float = -1.0,
    stdp_enabled: bool = True,
    a_plus: float = 0.1,
    a_minus: float = 0.1,
    tau_plus: float = 20.0,
    tau_minus: float = 20.0,
) -> CompiledNetwork:
    """
    Create a simple STDP network for the MVE.
    
    This is a convenience function that bypasses the full genome
    for quick testing.
    """
    compiled = CompiledNetwork()
    
    # Neuron models
    eqs = '''
    dv/dt = (v_rest - v + r * I) / tau_m : volt (unless refractory)
    v_rest : volt (shared)
    r : ohm (shared)
    tau_m : second (shared)
    I : amp
    '''
    
    # Excitatory population
    exc = b2.NeuronGroup(
        n_exc,
        eqs,
        method='exact',
        refractory='2 * ms',
        threshold='v > -50 * mV',
        reset='v = -70 * mV',
        name='exc',
    )
    exc.v = '-70 * mV'
    exc.I = '0 * amp'
    exc.tau_m = '10 * ms'
    exc.r = '1 * Mohm'
    exc.v_rest = '-70 * mV'
    
    # Inhibitory population
    inh = b2.NeuronGroup(
        n_inh,
        eqs,
        method='exact',
        refractory='1.5 * ms',
        threshold='v > -50 * mV',
        reset='v = -80 * mV',
        name='inh',
    )
    inh.v = '-80 * mV'
    inh.I = '0 * amp'
    inh.tau_m = '8 * ms'
    inh.r = '1 * Mohm'
    inh.v_rest = '-80 * mV'
    
    compiled.add_neuron_group('exc', exc)
    compiled.add_neuron_group('inh', inh)
    
    # Spike monitors
    exc_mon = b2.SpikeMonitor(exc, name='exc_spikes')
    inh_mon = b2.SpikeMonitor(inh, name='inh_spikes')
    compiled.add_spike_monitor('exc', exc_mon)
    compiled.add_spike_monitor('inh', inh_mon)
    
    # Add noise
    # For now, skip noise to make STDP effects clearer
    
    # Connectivity
    # exc -> exc (STDP)
    if stdp_enabled:
        S_ee = b2.Synapses(
            exc, exc,
            STDP_MODEL,
            on_pre=STDP_ON_PRE,
            on_post=STDP_ON_POST,
            delay=1.0 * b2.ms,
            name='exc_to_exc',
        )
        S_ee.connect(p=conn_prob)
        S_ee.w = w_exc
        S_ee.tau_plus = tau_plus * b2.ms
        S_ee.tau_minus = tau_minus * b2.ms
        S_ee.a_plus = a_plus
        S_ee.a_minus = a_minus
        S_ee.w_min = 0.0
        S_ee.w_max = 2.0
        compiled.add_synapse_group('exc_to_exc', S_ee)
    else:
        S_ee = b2.Synapses(exc, exc, 'w : 1', on_pre='v_post += w * mV', delay=1.0 * b2.ms, name='exc_to_exc')
        S_ee.connect(p=conn_prob)
        S_ee.w = w_exc
        compiled.add_synapse_group('exc_to_exc', S_ee)
    
    # exc -> inh
    S_ei = b2.Synapses(exc, inh, on_pre=f'v_post += {w_exc * 0.8} * mV', delay=0.5 * b2.ms, name='exc_to_inh')
    S_ei.connect(p=conn_prob * 2)
    compiled.add_synapse_group('exc_to_inh', S_ei)
    
    # inh -> exc
    S_ie = b2.Synapses(inh, exc, on_pre=f'v_post += {w_inh * 1.5} * mV', delay=0.5 * b2.ms, name='inh_to_exc')
    S_ie.connect(p=conn_prob * 2)
    compiled.add_synapse_group('inh_to_exc', S_ie)
    
    # inh -> inh
    S_ii = b2.Synapses(inh, inh, on_pre=f'v_post += {w_inh} * mV', delay=0.5 * b2.ms, name='inh_to_inh')
    S_ii.connect(p=conn_prob)
    compiled.add_synapse_group('inh_to_inh', S_ii)
    
    # Build network
    compiled.build_network()
    
    return compiled


