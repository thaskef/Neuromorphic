def _read_weight_bounds(synapses: b2.Synapses) -> Tuple[float, float]:
    """Return (w_min, w_max) for a plastic synapse group, else (0.0, inf)."""
    w_min, w_max = 0.0, float("inf")
    if len(synapses) == 0:
        return w_min, w_max
    if "w_min" in synapses.variables:
        w_min = float(np.min(np.asarray(synapses.w_min)))
    if "w_max" in synapses.variables:
        w_max = float(np.max(np.asarray(synapses.w_max)))
    return w_min, w_max


def _normalize_incoming_weights(
    synapses: b2.Synapses,
    target_sums: np.ndarray,
    w_min: float = 0.0,
    w_max: float = float("inf"),
) -> None:
    """
    Rescale each post-synaptic neuron's incoming weights so their sum returns
    to ``target_sums[j]`` (multiplicative synaptic scaling, Turrigiano 1998).

    The relative weight structure that fast plasticity (STDP) shaped is
    preserved; only the global drift (runaway depression/potentiation) is
    removed. Weights are re-clipped to ``[w_min, w_max]`` so this agrees with
    the plasticity bounds.
    """
    if len(synapses) == 0:
        return
    w = np.asarray(synapses.w, dtype=float)
    j = np.asarray(synapses.j, dtype=int)
    n_post = len(synapses.target)
    sums = np.bincount(j, weights=w, minlength=n_post)
    scale = np.ones(n_post, dtype=float)
    nz = sums > 1e-12
    scale[nz] = target_sums[nz] / sums[nz]
    # Bound the per-step rescaling factor for numerical stability.
    scale = np.clip(scale, 1e-3, 1e3)
    w = w * scale[j]
    if w_min > 0.0 or np.isfinite(w_max):
        w = np.clip(w, w_min, w_max)
    synapses.w = w


def _make_weight_normalization_operation(
    synapses: b2.Synapses,
    interval_ms: float,
    name: str,
) -> b2.NetworkOperation:
    """
    Build a scheduled operation that normalizes ``synapses`` every
    ``interval_ms`` ms of simulated time.

    The target is each neuron's *initial* incoming weight sum, captured before
    simulation. This holds the network's recurrent drive at its starting point
    while STDP reshapes the distribution of individual weights.
    """
    w0 = np.asarray(synapses.w, dtype=float)
    j0 = np.asarray(synapses.j, dtype=int)
    target_sums = np.bincount(j0, weights=w0, minlength=len(synapses.target))
    w_min, w_max = _read_weight_bounds(synapses)

    def _normalize() -> None:
        _normalize_incoming_weights(synapses, target_sums, w_min=w_min, w_max=w_max)

    return b2.NetworkOperation(
        _normalize,
        dt=interval_ms * b2.ms,
        name=name,
    )


def apply_homeostatic_rule(
    compiled: CompiledNetwork,
    rule: Any,
) -> None:
    """
    Apply a ``HomeostaticRule`` to a compiled network.

    Supported mechanisms (see [[Neuromorphic_Homeostasis_Implementation]]):

    - ``WEIGHT_NORMALIZATION``: keep each post-synaptic neuron's incoming
      weight sum at its initial value, on a slow clock. ``applies_to`` names the
      connection (synapse group) to normalize.
    """
    from genome_schema import HomeostaticMechanism

    interval_ms = rule.apply_interval if rule.apply_interval is not None else 100.0

    if rule.mechanism == HomeostaticMechanism.WEIGHT_NORMALIZATION:
        for name in rule.applies_to:
            if name not in compiled.synapse_groups:
                print(
                    f"Warning: homeostatic rule '{rule.name}' references "
                    f"unknown connection '{name}'; skipping."
                )
                continue
            op = _make_weight_normalization_operation(
                compiled.synapse_groups[name],
                interval_ms=interval_ms,
                name=f"homeo_{rule.name}_{name}",
            )
            compiled.network_operations.append(op)
    else:
        print(
            f"Warning: homeostatic mechanism '{rule.mechanism}' "
            f"not yet implemented."
        )


