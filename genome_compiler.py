def compile_lif_neuron(
    name: str,
    spec: NeuronTypeSpec,
    size: int,
    noise_std: float = 0.0,
) -> b2.NeuronGroup:
    """
    Compile a LIF neuron group from specification.
    
    Args:
        name: Name for the neuron group
        spec: Neuron type specification
        size: Number of neurons
        noise_std: Noise standard deviation
    
    Returns:
        Brian2 NeuronGroup
    """
    # LIF equations. v_rest/r/tau_m are declared as shared constants so they
    # can be assigned after construction (Brian2 does not infer undeclared names).
    #
    # If ``spec.tau_slow`` is set, the neuron also carries a slow NMDA-like
    # current ``g_nmda`` (units of volt) that decays with time constant
    # ``tau_slow``. Recurrent synapses compiled with ``slow_channel=True``
    # charge this current instead of ``v``, so a stimulus-elicited pattern can
    # be held across a delay (working memory; Wang 1999 / Compte et al. 2000).
    #
    # If ``spec.tau_adapt`` and ``spec.increment`` are set, the neuron also
    # carries a spike-frequency-adaptation current ``g_adapt`` (units of volt)
    # that steps up by ``increment`` mV on every spike and decays with time
    # constant ``tau_adapt``. Adaptation is the slow *negative* feedback that
    # balances the slow NMDA *positive* feedback, turning the otherwise
    # collapse-or-runaway recurrent network into a bistable attractor that can
    # hold a moderate firing rate through a delay (Compte et al. 2000).
    tau_slow = getattr(spec, 'tau_slow', None)
    has_slow = tau_slow not in (None, 0.0)
    tau_adapt = getattr(spec, 'tau_adapt', None)
    increment = getattr(spec, 'increment', None)
    has_adapt = tau_adapt not in (None, 0.0)

    drive = "r * I"
    slow_line = ""
    adapt_line = ""
    if has_slow:
        drive += " + g_nmda"
        slow_line = f"    dg_nmda/dt = -g_nmda / ({float(tau_slow)} * ms) : volt\n"
    if has_adapt:
        drive += " - g_adapt"
        adapt_line = f"    dg_adapt/dt = -g_adapt / ({float(tau_adapt)} * ms) : volt\n"

    noise_term = ""
    method = 'exact'
    if noise_std > 0:
        # Add Gaussian white membrane-potential noise of amplitude noise_std (mV).
        noise_term = f" + ({noise_std} * mV) * xi * tau_m**-0.5"
        method = 'euler'

    eqs = f'''
    dv/dt = (v_rest - v + {drive}) / tau_m{noise_term} : volt (unless refractory)
{slow_line}{adapt_line}    v_rest : volt (shared)
    r : ohm (shared)
    tau_m : second (shared)
    I : amp
    '''

    reset = f'v = {spec.v_reset} * mV'
    if has_adapt:
        reset += f'\n    g_adapt += {float(increment)} * mV'

    group = b2.NeuronGroup(
        size,
        eqs,
        method=method,
        refractory=f'{spec.tau_ref} * ms',
        threshold=f'v > {spec.v_thresh} * mV',
        reset=reset,
        name=name,
    )
    
    # Set initial values and constant parameters
    group.v = f'{spec.v_rest} * mV'
    group.v_rest = f'{spec.v_rest} * mV'
    group.r = f'{spec.r} * Mohm'
    group.tau_m = f'{spec.tau_m} * ms'
    group.I = '0 * amp'
    if has_slow:
        group.g_nmda = '0 * mV'
    if has_adapt:
        group.g_adapt = '0 * mV'
    
    return group


def compile_adaptive_lif_neuron(
    name: str,
    spec: NeuronTypeSpec,
    size: int,
    noise_std: float = 0.0,
) -> b2.NeuronGroup:
    """
    Compile an Adaptive LIF neuron group from specification.
    """
    eqs = '''
    dv/dt = (v_rest - v + r * I - w) / tau_m : volt (unless refractory)
    dw/dt = (a - w) / tau_adapt : amp
    a : amp
    I : amp
    '''
    
    if noise_std > 0:
        eqs += f'''
    xi : 1
    I_noise = {noise_std} * mV * xi : amp
    I = I + I_noise
    '''
    
    # Calculate 'a' parameter for adaptation
    # w increases by 'increment' per spike, decays with tau_adapt
    # At steady state: a = increment * firing_rate
    # For now, set a to 0 and handle adaptation through reset
    
    group = b2.NeuronGroup(
        size,
        eqs,
        method='exact',
        refractory=f'{spec.tau_ref} * ms',
        threshold=f'v > {spec.v_thresh} * mV',
        reset=f'''
        v = {spec.v_reset} * mV
        w = w + {spec.increment} * mV
        ''',
        name=name,
    )
    
    group.v = f'{spec.v_rest} * mV'
    group.w = '0 * mV'
    group.a = '0 * amp'
    
    return group


def compile_neuron_group(
    name: str,
    spec: NeuronTypeSpec,
    size: int,
    noise_std: float = 0.0,
) -> b2.NeuronGroup:
    """
    Compile a neuron group based on the neuron type specification.
    
    Dispatches to the appropriate compiler based on the model type.
    """
    from genome_schema import NeuronModel
    
    if spec.model == NeuronModel.LIF:
        return compile_lif_neuron(name, spec, size, noise_std)
    elif spec.model == NeuronModel.ADAPTIVE_LIF:
        return compile_adaptive_lif_neuron(name, spec, size, noise_std)
    else:
        # Fall back to LIF for unsupported models
        print(f"Warning: Neuron model {spec.model} not yet implemented. Falling back to LIF.")
        return compile_lif_neuron(name, spec, size, noise_std)


