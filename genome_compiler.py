def create_connectivity_matrix(
    source_size: int,
    target_size: int,
    pattern: ConnectivityPattern,
    probability: Optional[float] = None,
    k: Optional[int] = None,
    beta: Optional[float] = None,
    m: Optional[int] = None,
    allow_autapse: bool = False,
    rng: Optional[np.random.Generator] = None,
) -> np.ndarray:
    """
    Create a connectivity matrix based on the specified pattern.
    
    Args:
        source_size: Number of neurons in source population
        target_size: Number of neurons in target population
        pattern: Connectivity pattern type
        probability: Connection probability (for SPARSE_RANDOM)
        k: Number of neighbors (for SMALL_WORLD)
        beta: Rewiring probability (for SMALL_WORLD)
        m: Edges per new node (for SCALE_FREE)
        allow_autapse: Whether to allow self-connections
        rng: Random number generator
    
    Returns:
        Boolean connectivity matrix of shape (source_size, target_size)
    """
    from genome_schema import ConnectivityPattern

    if rng is None:
        rng = np.random.default_rng()
    
    if pattern == ConnectivityPattern.FULL:
        matrix = np.ones((source_size, target_size), dtype=bool)
        if not allow_autapse:
            np.fill_diagonal(matrix, False)
        return matrix
    
    elif pattern == ConnectivityPattern.SPARSE_RANDOM:
        if probability is None:
            raise ValueError("SPARSE_RANDOM requires probability parameter")
        matrix = rng.random((source_size, target_size)) < probability
        if not allow_autapse:
            np.fill_diagonal(matrix, False)
        return matrix
    
    elif pattern == ConnectivityPattern.SMALL_WORLD:
        if k is None or beta is None:
            raise ValueError("SMALL_WORLD requires k and beta parameters")
        # Create small-world network (Watts-Strogatz)
        # For simplicity, create a ring and rewire
        matrix = np.zeros((source_size, target_size), dtype=bool)
        
        # Only implement for square matrices
        if source_size == target_size:
            # Create ring connections
            for i in range(source_size):
                for j in range(1, k // 2 + 1):
                    idx1 = (i + j) % source_size
                    idx2 = (i - j) % source_size
                    matrix[i, idx1] = True
                    matrix[i, idx2] = True
            
            # Rewire with probability beta
            for i in range(source_size):
                for j in range(source_size):
                    if matrix[i, j] and i != j:
                        if rng.random() < beta:
                            # Rewire to random neuron
                            new_j = rng.integers(0, source_size)
                            while new_j == i or matrix[i, new_j]:
                                new_j = rng.integers(0, source_size)
                            matrix[i, j] = False
                            matrix[i, new_j] = True
        else:
            # Fall back to sparse random for non-square
            p = (k * 2) / target_size
            matrix = rng.random((source_size, target_size)) < p
        
        if not allow_autapse:
            np.fill_diagonal(matrix, False)
        return matrix
    
    elif pattern == ConnectivityPattern.ERDOS_RENYI:
        if probability is None:
            probability = 0.1  # Default
        return create_connectivity_matrix(
            source_size, target_size, ConnectivityPattern.SPARSE_RANDOM,
            probability=probability, allow_autapse=allow_autapse, rng=rng
        )
    
    elif pattern == ConnectivityPattern.GRID:
        # Create 2D grid connectivity
        # For now, fall back to sparse random
        if probability is None:
            probability = 0.05
        return create_connectivity_matrix(
            source_size, target_size, ConnectivityPattern.SPARSE_RANDOM,
            probability=probability, allow_autapse=allow_autapse, rng=rng
        )
    
    elif pattern == ConnectivityPattern.TORUS:
        # Similar to grid but with wrap-around
        if probability is None:
            probability = 0.05
        return create_connectivity_matrix(
            source_size, target_size, ConnectivityPattern.SPARSE_RANDOM,
            probability=probability, allow_autapse=allow_autapse, rng=rng
        )
    
    elif pattern == ConnectivityPattern.SCALE_FREE:
        # Barabasi-Albert scale-free network
        # For simplicity, use sparse random with power-law-ish distribution
        if probability is None:
            probability = 0.01
        return create_connectivity_matrix(
            source_size, target_size, ConnectivityPattern.SPARSE_RANDOM,
            probability=probability, allow_autapse=allow_autapse, rng=rng
        )
    
    else:
        # Default to sparse random
        if probability is None:
            probability = 0.02
        return create_connectivity_matrix(
            source_size, target_size, ConnectivityPattern.SPARSE_RANDOM,
            probability=probability, allow_autapse=allow_autapse, rng=rng
        )


