class GenomeCompiler:
    """
    Compiles a DevelopmentalGenome into a Brian2 network.
    
    This is the main class that orchestrates the compilation process.
    """
    
    def __init__(self, seed: Optional[int] = None):
        """
        Initialize the compiler.
        
        Args:
            seed: Random seed for reproducibility
        """
        self.seed = seed
        self.rng = np.random.default_rng(seed)
        
    def compile(self, genome: 'DevelopmentalGenome') -> CompiledNetwork:
        """
        Compile a genome into a Brian2 network.
        
        Args:
            genome: The developmental genome to compile
        
        Returns:
            CompiledNetwork containing all Brian2 objects
        """
        compiled = CompiledNetwork()
        
        # Step 1: Create neuron groups
        print("Compiling neuron populations...")
        neuron_groups = {}
        for pop_spec in genome.populations:
            neuron_type = genome.get_neuron_type(pop_spec.neuron_type)
            if neuron_type is None:
                raise ValueError(f"Neuron type '{pop_spec.neuron_type}' not found")
            
            group = compile_neuron_group(
                name=pop_spec.name,
                spec=neuron_type,
                size=pop_spec.size,
                noise_std=pop_spec.noise_std,
            )
            neuron_groups[pop_spec.name] = group
            compiled.add_neuron_group(pop_spec.name, group)
            
            # Add spike monitor for this population
            spike_mon = b2.SpikeMonitor(group, name=f"spike_mon_{pop_spec.name}")
            compiled.add_spike_monitor(pop_spec.name, spike_mon)
        
        # Step 2: Create connectivity
        print("Compiling connectivity...")
        neuromodulator_level = _neuromodulator_level(genome)
        for conn_spec in genome.connectivity_rules:
            source_group = neuron_groups[conn_spec.source]
            target_group = neuron_groups[conn_spec.target]
            
            synapse_type = genome.get_synapse_type(conn_spec.synapse_type)
            if synapse_type is None:
                raise ValueError(f"Synapse type '{conn_spec.synapse_type}' not found")
            
            # Create connectivity matrix
            connectivity = create_connectivity_matrix(
                source_size=len(source_group),
                target_size=len(target_group),
                pattern=conn_spec.pattern,
                probability=conn_spec.probability,
                k=conn_spec.k,
                beta=conn_spec.beta,
                m=conn_spec.m,
                allow_autapse=conn_spec.allow_autapse,
                rng=self.rng,
            )
            
            # Compile synapses
            synapses = compile_synapses(
                source=source_group,
                target=target_group,
                synapse_spec=synapse_type,
                connectivity=connectivity,
                name=conn_spec.name,
                neuromodulator_level=neuromodulator_level,
            )
            compiled.add_synapse_group(conn_spec.name, synapses)
        
        # Step 3: Apply plasticity rules
        print("Applying plasticity rules...")
        for rule in genome.plasticity_rules:
            for syn_name in rule.applies_to:
                if syn_name in compiled.synapse_groups:
                    apply_plasticity_rule(
                        compiled.synapse_groups[syn_name],
                        rule,
                    )

        # Step 3.5: Apply homeostatic rules (slow-timescale stabilizers)
        print("Applying homeostatic rules...")
        for rule in genome.homeostatic_rules:
            apply_homeostatic_rule(compiled, rule)

        # Step 4: Build network
        compiled.build_network()
        
        print(f"Compilation complete: {sum(compiled.population_sizes.values())} neurons, {sum(compiled.connection_counts.values())} connections")
        
        # Store neuromodulator config and the initial gate level so the harness
        # can drive reward-gated (three-factor) plasticity at runtime.
        compiled.neuromodulators = list(genome.neuromodulators)
        compiled.neuromodulator_level = neuromodulator_level
        
        return compiled


