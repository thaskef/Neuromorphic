class CompiledNetwork:
    """
    Container for a compiled Brian2 network.
    
    Holds all Brian2 objects, state trackers, and metadata needed
    to run and observe the network.
    """
    
    def __init__(self):
        # Brian2 groups and synapses
        self.neuron_groups: Dict[str, b2.NeuronGroup] = {}
        self.synapse_groups: Dict[str, b2.Synapses] = {}
        
        # State trackers
        self.spike_monitors: Dict[str, b2.SpikeMonitor] = {}
        self.state_monitors: Dict[str, b2.StateMonitor] = {}
        
        # Network metadata
        self.population_sizes: Dict[str, int] = {}
        self.connection_counts: Dict[str, int] = {}
        
        # Runtime state
        self.net: Optional[b2.Network] = None
        self.run_time: float = 0.0
        
        # Homeostatic / scheduled operations (added to the network at build time)
        self.network_operations: List[b2.NetworkOperation] = []
        
        # Observable values
        self.observable_cache: Dict[str, Any] = {}
        
        # Neuromodulator state (three-factor gating). ``neuromodulators`` holds
        # the genome's NeuromodulatorSpec list; ``neuromodulator_level`` is the
        # running dopamine gate D applied to THREE_FACTOR synapses.
        self.neuromodulators: List[Any] = []
        self.neuromodulator_level: float = 0.0
    
    def add_neuron_group(self, name: str, group: b2.NeuronGroup):
        """Register a neuron group."""
        self.neuron_groups[name] = group
        self.population_sizes[name] = len(group)
    
    def add_synapse_group(self, name: str, synapses: b2.Synapses):
        """Register a synapse group."""
        self.synapse_groups[name] = synapses
        self.connection_counts[name] = len(synapses)
    
    def add_spike_monitor(self, name: str, monitor: b2.SpikeMonitor):
        """Register a spike monitor."""
        self.spike_monitors[name] = monitor
    
    def add_state_monitor(self, name: str, monitor: b2.StateMonitor):
        """Register a state monitor."""
        self.state_monitors[name] = monitor
    
    def build_network(self):
        """Build the Brian2 Network container."""
        self.net = b2.Network()
        self.net.add(self.neuron_groups.values())
        self.net.add(self.synapse_groups.values())
        self.net.add(self.spike_monitors.values())
        self.net.add(self.state_monitors.values())
        self.net.add(self.network_operations)
    
    def run(self, duration: float, report: str = 'text'):
        """Run the network for a duration."""
        if self.net is None:
            self.build_network()
        
        self.net.run(duration * b2.ms, report=report)
        self.run_time += duration
    
    def reset_transient_state(self):
        """Reset transient activity state, preserving learned weights.

        Working memory operates on a faster timescale than plasticity: between
        trials the membrane potential and the slow currents should return to
        baseline while the STDP-shaped synaptic weights persist. Without this,
        the slow adaptation current (tau_adapt ~ hundreds of ms vs a ~700 ms
        trial) accumulates a floor across trials and biases the network toward
        the silent attractor state, degrading delay maintenance.
        """
        for group in self.neuron_groups.values():
            group.v = group.v_rest
            if 'g_nmda' in group.variables:
                group.g_nmda = 0 * b2.mV
            if 'g_adapt' in group.variables:
                group.g_adapt = 0 * b2.mV
    
    def set_neuromodulator_level(self, level: float) -> None:
        """Set the neuromodulator gate ``D`` on every three-factor synapse.

        ``D`` scales the STDP weight update by ``(1 + D)``, so a positive level
        (reward) reinforces plasticity and a negative level (punishment)
        suppresses it.
        """
        self.neuromodulator_level = float(level)
        for sg in self.synapse_groups.values():
            if 'D' in sg.variables:
                sg.D = self.neuromodulator_level
    
    def apply_reward(self, reward: float, elapsed_ms: float = 0.0) -> float:
        """Update the neuromodulator level in response to a trial outcome.

        For each neuromodulator, releases on reward (``trigger_on_reward``) or
        suppresses on error (``trigger_on_error``), then decays the level toward
        its baseline over ``elapsed_ms`` (the trial duration). Returns the new
        level so the harness can log it.
        """
        for nm in self.neuromodulators:
            baseline = getattr(nm, 'baseline', 0.0)
            release = getattr(nm, 'release_amount', 1.0)
            tau_decay = getattr(nm, 'tau_decay', None)
            trigger_reward = getattr(nm, 'trigger_on_reward', False)
            trigger_error = getattr(nm, 'trigger_on_error', False)

            # Decay toward baseline over the elapsed trial time.
            if tau_decay and elapsed_ms > 0.0:
                decay = float(np.exp(-elapsed_ms / tau_decay))
                self.neuromodulator_level = baseline + (self.neuromodulator_level - baseline) * decay

            # Release (reward) or suppress (error).
            if reward > 0.0 and trigger_reward:
                self.neuromodulator_level += release
            elif reward < 0.0 and trigger_error:
                self.neuromodulator_level -= release

        self.set_neuromodulator_level(self.neuromodulator_level)
        return self.neuromodulator_level
    
    def get_firing_rate(self, population: str, window: float = 100.0) -> float:
        """Get mean firing rate for a population over the last window ms."""
        if population not in self.spike_monitors:
            return 0.0
        
        monitor = self.spike_monitors[population]
        # Get spikes in the last window
        mask = (monitor.t / b2.ms) >= (self.run_time - window)
        n_spikes = np.sum(mask)
        n_neurons = self.population_sizes[population]
        
        if window <= 0:
            return 0.0
        
        return (n_spikes / n_neurons) / (window / 1000.0)  # Hz
    
    def get_mean_weight(self, connection_name: str) -> float:
        """Get mean weight for a synapse group."""
        if connection_name not in self.synapse_groups:
            return 0.0
        
        synapses = self.synapse_groups[connection_name]
        if len(synapses) == 0:
            return 0.0
        
        return np.mean(synapses.w)
    
    def get_spike_count(self, population: str) -> int:
        """Get total spike count for a population."""
        if population not in self.spike_monitors:
            return 0
        return len(self.spike_monitors[population].t)


