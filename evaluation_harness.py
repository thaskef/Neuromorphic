"""
Neuromorphic Co-Development Framework - Evaluation Harness

Runs multiple delayed match-to-sample (DMS) trials against a compiled genome,
aggregates accuracy and observables, and packages the result for the LLM
interface. This is checklist step 4 of the seed task spec:

    "run trials, compute accuracy, return observables to LLM."

The harness is a thin orchestration layer over ``TrialRunner``: it does not
reset network state between trials (so plasticity and attractor formation carry
over), collects per-trial ``TrialResult`` objects, and reduces them to the
metrics the LLM and the MVE success criteria care about.

Author: Generated by Mistral Vibe
Date: 2026-09-02
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional

import numpy as np
import brian2 as b2

from genome_compiler import CompiledNetwork
from trial_runner import TrialRunner, TrialResult


# Firing rate (Hz) above which a sensory feature is considered "ON".
# With rate_on=50 Hz and input_weight=20 mV, ON features fire ~15-25 Hz and
# OFF features fire ~0 Hz, so this threshold cleanly separates the two.
ON_RATE_THRESHOLD = 5.0


@dataclass
class EvaluationResult:
    """Aggregate metrics for a block of trials, shaped for LLM consumption."""

    n_trials: int
    n_correct: int
    accuracy: float          # overall fraction correct
    match_accuracy: float    # fraction correct on match trials
    non_match_accuracy: float  # fraction correct on non-match trials
    mean_reward: float       # mean +/-1 reward over trials

    mean_similarity_match: float       # readout score on match trials
    mean_similarity_nonmatch: float    # readout score on non-match trials

    # Observables (LLM-facing)
    sensory_on_rate: float        # mean rate (Hz) of ON features during sample
    sensory_off_rate: float       # mean rate (Hz) of OFF features during sample
    encoding_accuracy: float      # fraction of features correctly encoded
    assoc_sample_rate: float      # mean assoc rate (Hz) during sample phase
    assoc_test_rate: float        # mean assoc rate (Hz) during test phase
    assoc_weight_mean: float      # final mean assoc_to_assoc weight
    assoc_weight_std: float       # final std assoc_to_assoc weight
    mean_reaction_time_ms: float  # time-to-first-assoc-spike in test phase

    # Working-memory diagnostics (MVE success criteria)
    delay_maintenance: float      # mean corr(sample, delay2): does the sample pattern persist?
    distractor_rejection: float   # mean corr(sample, delay2) - corr(distractor, delay2)

    per_trial: List[TrialResult] = field(default_factory=list)

    def to_dict(self) -> Dict[str, float]:
        """Flatten to a JSON-serialisable dict for the LLM interface."""
        return {
            "n_trials": self.n_trials,
            "n_correct": self.n_correct,
            "accuracy": self.accuracy,
            "match_accuracy": self.match_accuracy,
            "non_match_accuracy": self.non_match_accuracy,
            "mean_reward": self.mean_reward,
            "mean_similarity_match": self.mean_similarity_match,
            "mean_similarity_nonmatch": self.mean_similarity_nonmatch,
            "sensory_on_rate": self.sensory_on_rate,
            "sensory_off_rate": self.sensory_off_rate,
            "encoding_accuracy": self.encoding_accuracy,
            "assoc_sample_rate": self.assoc_sample_rate,
            "assoc_test_rate": self.assoc_test_rate,
            "assoc_weight_mean": self.assoc_weight_mean,
            "assoc_weight_std": self.assoc_weight_std,
            "mean_reaction_time_ms": self.mean_reaction_time_ms,
            "delay_maintenance": self.delay_maintenance,
            "distractor_rejection": self.distractor_rejection,
        }


class EvaluationHarness:
    """Runs a block of DMS trials and reduces them to aggregate observables."""

    def __init__(
        self,
        network: CompiledNetwork,
        n_features: int,
        n_neurons_per_feature: int,
        rate_on: float = 50.0,
        input_weight: float = 20.0,
        durations: Optional[Dict[str, float]] = None,
        readout_threshold: float = 0.3,
        associative_population: str = "associative",
        seed: Optional[int] = None,
        report: Optional[str] = None,
    ):
        """
        Parameters
        ----------
        network, n_features, n_neurons_per_feature, rate_on, input_weight,
        durations, readout_threshold, associative_population, seed:
            Forwarded to ``TrialRunner``.
        report:
            Brian2 run report mode. None silences per-trial progress output,
            which is desirable when running many trials.
        """
        self.network = network
        self.n_features = int(n_features)
        self.associative_population = associative_population
        self.runner = TrialRunner(
            network=network,
            n_features=n_features,
            n_neurons_per_feature=n_neurons_per_feature,
            rate_on=rate_on,
            input_weight=input_weight,
            durations=durations,
            readout_threshold=readout_threshold,
            associative_population=associative_population,
            seed=seed,
            report=report,
        )

    # ------------------------------------------------------------------
    # Per-trial helpers
    # ------------------------------------------------------------------
    def _reaction_time_ms(self) -> Optional[float]:
        """
        Coarse response-latency proxy: time from test-phase onset to the first
        associative spike. Returns None if the associative layer never fires
        during the test phase.
        """
        pop = self.associative_population
        mon = self.network.spike_monitors[pop]
        times = np.asarray(mon.t / b2.ms)
        t_test_start = self.runner.elapsed_ms + self.runner.offsets["test"]
        t_test_end = t_test_start + self.runner.durations["test"]
        in_test = (times >= t_test_start) & (times < t_test_end)
        if not in_test.any():
            return None
        return float(times[in_test].min() - t_test_start)

    def evaluate(self, n_trials: int = 100, progress: bool = True) -> EvaluationResult:
        """
        Run ``n_trials`` trials and return the aggregate ``EvaluationResult``.

        Network state is persistent: the genome is compiled once, and each
        trial advances the same simulation, so STDP accumulates across the
        block exactly as it would in a real experiment.
        """
        results: List[TrialResult] = []
        correct = 0
        match_correct = 0
        match_n = 0
        nonmatch_correct = 0
        nonmatch_n = 0

        sim_match = []
        sim_nonmatch = []
        on_rates = []
        off_rates = []
        assoc_sample_rates = []
        assoc_test_rates = []
        reaction_times = []
        delay_maintenance = []
        distractor_rejection = []
        n_features_encoded = 0
        n_features_total = 0

        for t in range(n_trials):
            stimuli = self.runner.generate_stimuli()
            result = self.runner.run_trial(stimuli)
            results.append(result)

            correct += int(result.correct)
            if result.test_is_match:
                match_n += 1
                match_correct += int(result.correct)
                sim_match.append(result.similarity)
            else:
                nonmatch_n += 1
                nonmatch_correct += int(result.correct)
                sim_nonmatch.append(result.similarity)

            # Sensory encoding fidelity, from the sample phase.
            sample = np.asarray(stimuli.sample, dtype=bool)
            sr = np.asarray(result.sensory_sample_rates)
            if sample.sum() > 0:
                on_rates.append(sr[sample].mean())
            if (~sample).sum() > 0:
                off_rates.append(sr[~sample].mean())

            # Per-feature correctness: ON feature should exceed threshold,
            # OFF feature should stay below it.
            n_features_encoded += int((sr[sample] > ON_RATE_THRESHOLD).sum()) + \
                                   int((sr[~sample] < ON_RATE_THRESHOLD).sum())
            n_features_total += self.n_features

            assoc_sample_rates.append(result.phase_stats["sample"].firing_rate)
            assoc_test_rates.append(result.phase_stats["test"].firing_rate)

            # Working memory: does the sample pattern persist through the delay
            # (delay2), and does it win out over the distractor?
            dm = self.runner._pearson(result.sample_pattern, result.delay2_pattern)
            dr = dm - self.runner._pearson(result.distractor_pattern, result.delay2_pattern)
            delay_maintenance.append(dm)
            distractor_rejection.append(dr)

            rt = self._reaction_time_ms()
            if rt is not None:
                reaction_times.append(rt)

            if progress:
                print(
                    f"trial {t + 1:3d}/{n_trials}: "
                    f"match={result.test_is_match!s:5s} "
                    f"decision={'match' if result.decision else 'non-match':9s} "
                    f"correct={result.correct!s:5s} "
                    f"sim={result.similarity:+.3f}"
                )

        # Final weight statistics of the plastic recurrent connection.
        assoc_weight_mean = self.network.get_mean_weight("assoc_to_assoc")
        w = np.asarray(self.network.synapse_groups["assoc_to_assoc"].w)
        assoc_weight_std = float(w.std()) if w.size else 0.0

        return EvaluationResult(
            n_trials=n_trials,
            n_correct=correct,
            accuracy=correct / n_trials if n_trials else 0.0,
            match_accuracy=match_correct / match_n if match_n else 0.0,
            non_match_accuracy=nonmatch_correct / nonmatch_n if nonmatch_n else 0.0,
            mean_reward=(2 * correct / n_trials - 1.0) if n_trials else 0.0,
            mean_similarity_match=float(np.mean(sim_match)) if sim_match else 0.0,
            mean_similarity_nonmatch=float(np.mean(sim_nonmatch)) if sim_nonmatch else 0.0,
            sensory_on_rate=float(np.mean(on_rates)) if on_rates else 0.0,
            sensory_off_rate=float(np.mean(off_rates)) if off_rates else 0.0,
            encoding_accuracy=n_features_encoded / n_features_total if n_features_total else 0.0,
            assoc_sample_rate=float(np.mean(assoc_sample_rates)) if assoc_sample_rates else 0.0,
            assoc_test_rate=float(np.mean(assoc_test_rates)) if assoc_test_rates else 0.0,
            assoc_weight_mean=float(assoc_weight_mean),
            assoc_weight_std=assoc_weight_std,
            mean_reaction_time_ms=float(np.mean(reaction_times)) if reaction_times else 0.0,
            delay_maintenance=float(np.mean(delay_maintenance)) if delay_maintenance else 0.0,
            distractor_rejection=float(np.mean(distractor_rejection)) if distractor_rejection else 0.0,
            per_trial=results,
        )


